"""---
## 💬 Paso 5: Función para hacer preguntas sobre la imagen

Creamos una función auxiliar que:
1. Preprocesa la imagen con el procesador de CLIP
2. Formatea el prompt en el formato que espera el modelo (LLaVA-style)
3. Genera la respuesta
"""

from geochat.conversation import conv_templates
from geochat.constants import IMAGE_TOKEN_INDEX, DEFAULT_IMAGE_TOKEN
from geochat.mm_utils import tokenizer_image_token, KeywordsStoppingCriteria
from PIL import Image
import torch

def preguntar_geochat(imagen_pil, pregunta, max_tokens=512):
    """
    Hace una pregunta a GeoChat sobre una imagen satelital.

    Args:
        imagen_pil: Imagen PIL en formato RGB
        pregunta: Pregunta en texto (puede ser en inglés o español)
        max_tokens: Longitud máxima de la respuesta

    Returns:
        Respuesta del modelo como string
    """
    # 1. Preprocesar la imagen
    image_tensor = image_processor.preprocess(imagen_pil, return_tensors='pt')['pixel_values']
    image_tensor = image_tensor.half().cuda()

    # 2. Crear la conversación en formato LLaVA v1
    conv = conv_templates['llava_v1'].copy()

    # El token <image> le indica al modelo dónde insertar las features visuales
    prompt_con_imagen = DEFAULT_IMAGE_TOKEN + '\n' + pregunta
    conv.append_message(conv.roles[0], prompt_con_imagen)  # USER
    conv.append_message(conv.roles[1], None)               # ASSISTANT (vacío)

    prompt = conv.get_prompt()

    # 3. Tokenizar
    input_ids = tokenizer_image_token(
        prompt, tokenizer, IMAGE_TOKEN_INDEX, return_tensors='pt'
    ).unsqueeze(0).cuda()

    # 4. Criterio de parada
    stop_str = conv.sep2 if conv.sep2 else conv.sep
    stopping_criteria = KeywordsStoppingCriteria([stop_str], tokenizer, input_ids)

    # 5. Generar respuesta
    with torch.inference_mode():
        output_ids = model.generate(
            input_ids,
            images=image_tensor,
            do_sample=True,
            temperature=0.2,
            max_new_tokens=max_tokens,
            use_cache=True,
            stopping_criteria=[stopping_criteria]
        )

    # 6. Decodificar
    respuesta = tokenizer.decode(
        output_ids[0, input_ids.shape[1]:], skip_special_tokens=True
    ).strip()

    if respuesta.endswith(stop_str):
        respuesta = respuesta[:-len(stop_str)].strip()

    return respuesta

print(' Función preguntar_geochat() lista para usar')

